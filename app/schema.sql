CREATE TABLE IF NOT EXISTS ac_users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(80) NOT NULL,
 username VARCHAR(60) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
 role ENUM('Owner','Staff') NOT NULL, active TINYINT NOT NULL DEFAULT 1
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ac_items (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL UNIQUE,
 category VARCHAR(40) NOT NULL, unit VARCHAR(12) NOT NULL, minimum BIGINT NOT NULL, archived TINYINT NOT NULL DEFAULT 0
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ac_lots (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, item_id INT UNSIGNED NOT NULL,
 expiry DATE NULL, balance BIGINT NOT NULL DEFAULT 0, INDEX(item_id,expiry),
 FOREIGN KEY(item_id) REFERENCES ac_items(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ac_moves (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, item_id INT UNSIGNED NOT NULL,
 user_id INT UNSIGNED NOT NULL, type VARCHAR(24) NOT NULL, delta BIGINT NOT NULL,
 after_qty BIGINT NOT NULL, note VARCHAR(255) NOT NULL, created DATETIME NOT NULL,
 request_key CHAR(32) NOT NULL UNIQUE, INDEX(item_id,created), INDEX(created),
 FOREIGN KEY(item_id) REFERENCES ac_items(id), FOREIGN KEY(user_id) REFERENCES ac_users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ac_lines (
 move_id INT UNSIGNED NOT NULL, lot_id INT UNSIGNED NOT NULL, delta BIGINT NOT NULL,
 PRIMARY KEY(move_id,lot_id), FOREIGN KEY(move_id) REFERENCES ac_moves(id),
 FOREIGN KEY(lot_id) REFERENCES ac_lots(id)
) ENGINE=InnoDB;
